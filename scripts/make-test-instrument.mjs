// Generates the tiny CC0 test instrument used by unit tests (expansion.md E0).
// Usage: node scripts/make-test-instrument.mjs
import { mkdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../app/public/instruments/test-sine/', import.meta.url);
mkdirSync(dir, { recursive: true });
const rate = 22050;
const seconds = 0.15;

function wav(midi) {
  const n = Math.round(rate * seconds);
  const data = Buffer.alloc(n * 2);
  const freq = 440 * 2 ** ((midi - 69) / 12);
  for (let i = 0; i < n; i++) {
    const t = i / rate;
    const env = Math.min(1, t / 0.005) * Math.exp(-t * 12);
    data.writeInt16LE(Math.round(Math.sin(2 * Math.PI * freq * t) * env * 0.5 * 32767), i * 2);
  }
  const header = Buffer.alloc(44);
  header.write('RIFF', 0); header.writeUInt32LE(36 + data.length, 4); header.write('WAVE', 8);
  header.write('fmt ', 12); header.writeUInt32LE(16, 16); header.writeUInt16LE(1, 20); header.writeUInt16LE(1, 22);
  header.writeUInt32LE(rate, 24); header.writeUInt32LE(rate * 2, 28); header.writeUInt16LE(2, 32); header.writeUInt16LE(16, 34);
  header.write('data', 36); header.writeUInt32LE(data.length, 40);
  return Buffer.concat([header, data]);
}

const roots = [48, 60, 72];
for (const root of roots) writeFileSync(new URL(`sine-${root}.wav`, dir), wav(root));

const manifest = {
  schemaVersion: 1,
  id: 'test-sine',
  name: 'Test Sine',
  family: 'other',
  version: 1,
  engine: 'sampler',
  defaultArticulation: 'sustain',
  maxPolyphony: 8,
  pitchShiftLimitSemitones: 6,
  preloadStrategy: 'all',
  envelope: { mode: 'one-shot', attackMs: 2, releaseMs: 30 },
  provenance: {
    source: 'MusicMaker test fixture',
    url: 'https://github.com/marx1980/MusicMaker/blob/main/scripts/make-test-instrument.mjs',
    creator: 'MusicMaker contributors (generated)',
    licence: 'CC0-1.0',
    obtained: '2026-10-30',
    redistribution: true,
    modification: true,
    processing: 'Synthesised sine tones, 22.05 kHz 16-bit mono',
  },
  regions: roots.map((root) => ({
    id: `sine-${root}`, file: `sine-${root}.wav`, rootMidi: root, lowMidi: root - 6, highMidi: root + 5,
    velocityLow: 1, velocityHigh: 127, articulation: 'sustain',
  })),
};
writeFileSync(new URL('manifest.json', dir), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(new URL('LICENCE.txt', dir), 'CC0 1.0 Universal. Generated by scripts/make-test-instrument.mjs for MusicMaker tests.\n');
