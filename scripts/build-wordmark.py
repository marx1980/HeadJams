"""Build the HeadJams wordmark as outlined paths (no font needed at runtime).

Head (follows the text colour) + vibration squiggle + Jams (gradient).
Usage: python3 scripts/build-wordmark.py <font.woff2> src/ui/wordmarkPaths.ts [head] [jams]
The current title is Fredoka 600, lowercase: head + jams.
The glyphs are converted to path data so the mark renders identically on every device.
"""
import math
import sys

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONT, OUT = sys.argv[1], sys.argv[2]
HEAD_T = sys.argv[3] if len(sys.argv) > 3 else 'Head'
JAMS_T = sys.argv[4] if len(sys.argv) > 4 else 'Jams'
CYAN, MAGENTA, ORANGE = '#19e0ff', '#ff4fd8', '#ffb02e'
K = 20.5                      # one squiggle unit, in font units (1000 per em)
BASE = 0                      # baseline in font coordinates

font = TTFont(FONT)
cmap = font.getBestCmap()
gs = font.getGlyphSet()
hmtx = font['hmtx']


def run(text, x0):
    """Return (path d, end x) for text at baseline BASE, starting at x0 (y flipped for SVG)."""
    pen = SVGPathPen(gs)
    x = x0
    for ch in text:
        name = cmap[ord(ch)]
        tp = TransformPen(pen, (1, 0, 0, -1, x, BASE))
        gs[name].draw(tp)
        x += hmtx[name][0]
    return pen.getCommands(), x


head_d, head_end = run(HEAD_T, 0)
GAP = 80                                  # .08em either side of the squiggle
SVG_W = 780                               # .78em box for the squiggle
svg_left = head_end + GAP
content_left = svg_left + (SVG_W - 34 * K) / 2     # viewBox is centred in its box
jams_x = svg_left + SVG_W + GAP
jams_d, jams_end = run(JAMS_T, jams_x)

# squiggle: viewBox x -2..32, y 0..40, drawn at baseline offset so its box sits like the CSS version
top = BASE - 720                          # 0.82em tall box, lifted 0.1em above the baseline
pts = []
for i in range(61):
    u = i * .5
    v = 20 + 9 * math.sin(u / 3.2) * math.sin(math.pi * u / 30)
    X = content_left + (u + 2) * K
    Y = top + v * K
    pts.append(f'{X:.1f},{Y:.1f}')
wave_d = 'M' + ' L'.join(pts)
wave_x1, wave_x2 = content_left, content_left + 30 * K

pad = 60
vb_x, vb_y = -pad, top - pad
vb_w = jams_end + pad - vb_x
vb_h = (BASE + 180) - vb_y
line_w = 4 * K

ts = f'''// Generated by scripts/build-wordmark.py from Fredoka 600 (lowercase). Do not edit by hand.
export const WORDMARK = {{
  viewBox: '{vb_x:.0f} {vb_y:.0f} {vb_w:.0f} {vb_h:.0f}',
  head: '{head_d}',
  jams: '{jams_d}',
  wave: '{wave_d}',
  waveWidth: {line_w:.1f},
  waveX: [{wave_x1:.1f}, {wave_x2:.1f}],
  jamsX: [{jams_x:.1f}, {jams_end:.1f}],
  colors: {{ cyan: '{CYAN}', magenta: '{MAGENTA}', orange: '{ORANGE}' }},
}};
'''
open(OUT, 'w').write(ts)
print('viewBox', vb_x, vb_y, vb_w, vb_h)
